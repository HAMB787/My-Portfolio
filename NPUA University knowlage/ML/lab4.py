import numpy as np

# ==========================================
# 1. ՏՎՅԱԼՆԵՐԻ ԲԱԶԱ (Վարկի հաստատում)
# ==========================================
# Սյունակներ՝ [Ազատ անդամ (1), Տարիք, Եկամուտ, Վարկ.Պատմություն, Պարտքեր]
X_train = np.array([
    [1, 30, 20, 5, 2],
    [1, 25, 15, 3, 10],
    [1, 40, 45, 8, 1],
    [1, 35, 30, 6, 8],
    [1, 22, 12, 2, 5],
    [1, 50, 40, 9, 2],
    [1, 28, 18, 4, 15],
    [1, 45, 35, 7, 5]
])
y_train = np.array([1, 0, 1, 1, 0, 1, 0, 1]) # 1 = Հաստատվել է, 0 = Մերժվել է

# Թեստային տվյալներ (9-րդ և 10-րդ հաճախորդներ)
X_test = np.array([
    [1, 32, 25, 6, 4],
    [1, 26, 14, 3, 12]
])
y_test = np.array([1, 0]) # Իրական արդյունքները

# ==========================================
# 2. ՆՅՈՒՏՈՆ-ՌԱՖՍՈՆԻ ԱԼԳՈՐԻԹՄԸ (Լաբորատոր 2)
# ==========================================

# ՔԱՅԼ 1. Սկզբնական արժեքների որոշում (բանաձև 2.5)
y_bar = np.mean(y_train)
w0_initial = np.log(y_bar / (1 - y_bar))

# Ստեղծում ենք w վեկտորը՝ w0-ն դնելով հաշվված արժեքը, մնացածը՝ 0
w = np.zeros(X_train.shape[1])
w[0] = w0_initial

print(f"--- Լոգիստիկ Ռեգրեսիայի Ուսուցում ---")
print(f"Սկզբնական կշիռներ (w_0): {np.round(w, 4)}")

# Պարամետրեր ինտերացիայի համար
max_iter = 100
delta_w_threshold = 1e-5 # Կանգառի պայման (բանաձև 2.10)

for i in range(max_iter):
    # a(x) հաշվարկ (բանաձև 2.6)
    a = np.dot(X_train, w)
    
    # p հավանականության հաշվարկ սիգմոիդով (բանաձև 2.7)
    # np.clip-ը ապահովագրում է, որ թվերը շատ չմեծանան կամ փոքրանան
    a = np.clip(a, -250, 250) 
    p = 1 / (1 + np.exp(-a))
    
    # v կշիռների վեկտորի հաշվարկ (բանաձև 2.8-ի ներքևի մասը)
    v = p * (1 - p)
    # Ապահովագրում զրոյի բաժանումից
    v = np.clip(v, 1e-10, 1) 
    V = np.diag(v) # Անկյունագծային մատրից
    
    # u վեկտորի հաշվարկ (բանաձև 2.8)
    u = a + (y_train - p) / v
    
    # Նոր կշիռների հաշվարկ (բանաձև 2.9) -> w = (X^T * V * X)^(-1) * X^T * V * u
    # Օգտագործում ենք np.linalg.solve՝ հակադարձ մատրիցի փոխարեն համակարգը լուծելու համար
    A_mat = np.dot(X_train.T, np.dot(V, X_train))
    # Կայունության համար գլխավոր անկյունագծին շատ փոքր թիվ ենք գումարում (Ridge)
    A_mat += np.eye(A_mat.shape[0]) * 1e-5 
    C_vec = np.dot(X_train.T, np.dot(V, u))
    
    w_new = np.linalg.solve(A_mat, C_vec)
    
    # Ստուգում ենք կանգառի պայմանը (բանաձև 2.10)
    diff = np.max(np.abs(w_new - w))
    w = w_new
    
    if diff <= delta_w_threshold:
        print(f"Ալգորիթմը զուգամիտեց {i+1} իտերացիայից հետո:")
        break

print(f"Վերջնական կշիռներ (W): {np.round(w, 4)}\n")

# ==========================================
# 3. ԹԵՍՏԱՎՈՐՈՒՄ ԵՎ ՈՐԱԿԻ ԳՆԱՀԱՏՈՒՄ
# ==========================================

# Թեստային տվյալների վրա հաշվում ենք a(x) և p հավանականությունը
a_test = np.dot(X_test, w)
p_test = 1 / (1 + np.exp(-np.clip(a_test, -250, 250)))

# Քանի որ սա դասակարգում է, եթե հավանականությունը >= 0.5, դասը 1 է, հակառակ դեպքում՝ 0
y_pred = (p_test >= 0.5).astype(int)

print("--- Թեստավորում (9-րդ և 10-րդ հաճախորդներ) ---")
for idx in range(len(y_test)):
    print(f"Հաճախորդ {idx+9}: Հավանականություն = {p_test[idx]:.4f} -> Կանխատեսում: {y_pred[idx]} (Իրական: {y_test[idx]})")

# Որակի գնահատում (Ճշտություն - Accuracy)
accuracy = np.mean(y_pred == y_test) * 100
print(f"\nՄոդելի Ճշտությունը (Accuracy) թեստային բազմության վրա: {accuracy}%")



# ==========================================
# 4. ԿԱՆԽԱՏԵՍՈՒՄ ՆՈՐ ՕԲՅԵԿՏՆԵՐԻ ՀԱՄԱՐ
# ==========================================

# Նոր հաճախորդների տվյալները՝ [Ազատ անդամ, Տարիք, Եկամուտ, Վարկ.Պատմություն, Պարտքեր]
X_new = np.array([
    [1, 30, 40, 8, 2],  # Նոր հաճախորդ 1 (Լավ պրոֆիլ)
    [1, 22, 15, 2, 12], # Նոր հաճախորդ 2 (Ռիսկային պրոֆիլ)
    [1, 35, 25, 5, 6]   # Նոր հաճախորդ 3 (Միջին պրոֆիլ)
])

print("\n--- Կանխատեսում Նոր Հաճախորդների Համար ---")
a_new = np.dot(X_new, w)
p_new = 1 / (1 + np.exp(-np.clip(a_new, -250, 250)))

for i, p in enumerate(p_new):
    decision = "Կհաստատվի (1)" if p >= 0.5 else "Կմերժվի (0)"
    print(f"Նոր հաճախորդ {i+1}: Հավանականություն = {p * 100:.2f}% -> {decision}")